// where they have the food, SR Legacy otherwise, and FNDDS for dishes as they're eaten (mash, burgers, pizza).
import type { CatalogFood } from './types'

interface CommonFood extends CatalogFood {
  /** Other words people search with, like "ground beef" for mince. */
  aliases?: string
}

function food(
  fdcId: number,
  name: string,
  calories: number,
  protein: number,
  carbs: number,
  fat: number,
  aliases?: string
): CommonFood {
  return { id: `usda-${fdcId}`, name, per100g: { calories, protein, carbs, fat }, aliases }
}

